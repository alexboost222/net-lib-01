fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("report") => report(&args[1..]),
        Some("header") => header(args.iter().any(|a| a == "--check")),
        Some("log-catalog") => {
            let entries = logs::catalog(std::path::Path::new("."));
            let problems = logs::lint(&entries);
            if !problems.is_empty() {
                for p in problems {
                    eprintln!("{p}");
                }
                return ExitCode::FAILURE;
            }
            match std::fs::write("docs/LOG_EVENTS.md", logs::catalog_markdown(&entries)) {
                Ok(()) => {
                    eprintln!("wrote docs/LOG_EVENTS.md with {} events", entries.len());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::FAILURE
                }
            }
        }
        Some("unity-package") => match unity::run(&args[1..]) {
            Ok(out) => {
                print!("{out}");
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("{e}");
                ExitCode::FAILURE
            }
        },
        Some("coverage") => match coverage::run(&args[1..]) {
            Ok(out) => {
                print!("{out}");
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("{e}");
                ExitCode::FAILURE
            }
        },
        Some("logview") => match logs::logview(&args[1..]) {
            Ok(out) => {
                print!("{out}");
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("{e}");
                ExitCode::FAILURE
            }
        },
        _ => {
            eprintln!(
                "usage: cargo xtask report [--milestone M1] [--all] | header [--check] | log-catalog | logview FILE"
            );
            ExitCode::FAILURE
        }
    }
}

const HEADER: &str = "bindings/c/netlib.h";

fn header(check: bool) -> ExitCode {
    let config = cbindgen::Config {
        language: cbindgen::Language::C,
        include_guard: Some("NETLIB_H".into()),
        cpp_compat: true,
        documentation: true,
        autogen_warning: Some("/* Generated by `cargo xtask header`. Do not edit. */".into()),
        usize_is_size_t: true,
        ..cbindgen::Config::default()
    };
    let generated = match cbindgen::Builder::new()
        .with_crate("crates/netlib-ffi")
        .with_config(config)
        .generate()
    {
        Ok(b) => {
            let mut out = Vec::new();
            b.write(&mut out);
            out
        }
        Err(e) => {
            eprintln!("cbindgen failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    if check {
        let current = std::fs::read(HEADER).unwrap_or_default();
        if current != generated {
            eprintln!("{HEADER} is out of date: run `cargo xtask header`");
            return ExitCode::FAILURE;
        }
        eprintln!("{HEADER} is up to date");
        return ExitCode::SUCCESS;
    }
    let _ = std::fs::create_dir_all("bindings/c");
    match std::fs::write(HEADER, generated) {
        Ok(()) => {
            eprintln!("wrote {HEADER}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("cannot write {HEADER}: {e}");
            ExitCode::FAILURE
        }
    }
}

/// Evidence for coverage criteria from the last `cargo xtask coverage` run.
fn coverage_evidence(id: &str) -> (String, bool) {
    let Some(v) = std::fs::read_to_string(coverage::SUMMARY)
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
    else {
        return ("run `cargo xtask coverage`".into(), false);
    };
    let get = |k: &str| v[k].as_f64();
    let at_least = |k: &str, min: f64| match get(k) {
        Some(x) => (format!("{x:.1}% (≥ {min}%)"), x >= min),
        None => ("not measured".into(), false),
    };
    match id {
        "T1" => at_least("core_lines", coverage::CORE_LINES),
        "T2" => at_least("core_branches", coverage::CORE_BRANCHES),
        "T3" => {
            let crates = ["netlib", "netlib-ffi", "netlib-log", "netlib-sim"];
            let vals: Vec<(String, f64)> = crates
                .iter()
                .filter_map(|c| get(&format!("{c}_lines")).map(|x| (c.to_string(), x)))
                .collect();
            let pass = vals.len() == crates.len() && vals.iter().all(|(_, x)| *x >= coverage::OTHER_LINES);
            let text = vals
                .iter()
                .map(|(c, x)| format!("{c} {x:.1}%"))
                .collect::<Vec<_>>()
                .join(", ");
            (text, pass)
        }
        "T4" => at_least("core_mutation_score", coverage::MUTATION_SCORE),
        "T5" => at_least("dotnet_lines", coverage::DOTNET_LINES),
        "T7" => {
            let base = std::fs::read_to_string("coverage-baseline.json")
                .ok()
                .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok());
            match base {
                Some(b) => {
                    let drops: Vec<String> = b
                        .as_object()
                        .into_iter()
                        .flatten()
                        .filter_map(|(k, bv)| {
                            let d = get(k)? - bv.as_f64()?;
                            (d < -coverage::MAX_DROP).then(|| format!("{k} {d:+.1}"))
                        })
                        .collect();
                    if drops.is_empty() {
                        ("no drop against coverage-baseline.json".into(), true)
                    } else {
                        (drops.join(", "), false)
                    }
                }
                None => ("no coverage-baseline.json".into(), false),
            }
        }
        _ => {
            let all = ["T1", "T2", "T3", "T4", "T5"].iter().all(|t| coverage_evidence(t).1);
            ("T1-T5".into(), all)
        }
    }
}

fn run(cmd: &str, args: &[&str]) -> (bool, String) {
    eprintln!("$ {cmd} {}", args.join(" "));
    match Command::new(cmd).args(args).output() {
        Ok(o) => {
            let mut s = String::from_utf8_lossy(&o.stdout).into_owned();
            s.push_str(&String::from_utf8_lossy(&o.stderr));
            (o.status.success(), s)
        }
        Err(e) => (false, e.to_string()),
    }
}

/// Criterion ids encoded in a test name: `pk1_pk2_foo` -> `["PK1", "PK2"]`.
fn criteria_of(test: &str) -> Vec<String> {
    let name = test.rsplit("::").next().unwrap_or(test);
    name.split('_')
        .map_while(|part| {
            let letters = part.trim_end_matches(|c: char| c.is_ascii_digit());
            let valid =
                !letters.is_empty() && letters.len() < part.len() && letters.chars().all(|c| c.is_ascii_lowercase());
            valid.then(|| part.to_ascii_uppercase())
        })
        .collect()
}

#[derive(Default)]
struct Result {
    passed: Vec<String>,
    failed: Vec<String>,
}

fn report(args: &[String]) -> ExitCode {
    let mut milestone = "M1".to_string();
    let mut all = false;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--milestone" => milestone = it.next().cloned().unwrap_or_default().to_uppercase(),
            "--all" => all = true,
            other => {
                eprintln!("unknown argument {other}");
                return ExitCode::FAILURE;
            }
        }
    }
    let upto = MILESTONES.iter().position(|m| *m == milestone).unwrap_or(1);
    let in_scope = |m: &str| all || MILESTONES.iter().position(|x| *x == m).is_some_and(|i| i <= upto);

    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let (fmt_ok, _) = run(&cargo, &["fmt", "--all", "--check"]);
    let (clippy_ok, clippy_out) = run(
        &cargo,
        &[
            "clippy",
            "--workspace",
            "--all-targets",
            "--quiet",
            "--",
            "-D",
            "warnings",
        ],
    );
    let (deny_ok, deny_out) = run(&cargo, &["deny", "check"]);
    let deny_missing = deny_out.contains("no such command");
    let (tests_ok, test_out) = run(&cargo, &["test", "--workspace", "--no-fail-fast"]);

    let mut results: BTreeMap<String, Result> = BTreeMap::new();
    let mut total = (0usize, 0usize);
    for line in test_out.lines() {
        let Some(rest) = line.strip_prefix("test ") else {
            continue;
        };
        let Some((name, status)) = rest.rsplit_once(" ... ") else {
            continue;
        };
        let ok = match status.trim() {
            "ok" => true,
            "FAILED" => false,
            _ => continue,
        };
        total.0 += usize::from(ok);
        total.1 += 1;
        for id in criteria_of(name) {
            let r = results.entry(id).or_default();
            if ok { &mut r.passed } else { &mut r.failed }.push(name.to_string());
        }
    }
    // .NET binding tests, when the SDK is available: "  Passed ManagerTests.X3_Foo [1 ms]".
    let (dotnet_present, _) = run("dotnet", &["--version"]);
    if dotnet_present {
        let (_, out) = run(
            "dotnet",
            &[
                "test",
                "bindings/dotnet/NetLib.Tests",
                "--nologo",
                "--logger",
                "console;verbosity=normal",
            ],
        );
        for line in out.lines() {
            let line = line.trim();
            let (ok, rest) = match (line.strip_prefix("Passed "), line.strip_prefix("Failed ")) {
                (Some(r), _) => (true, r),
                (_, Some(r)) => (false, r),
                _ => continue,
            };
            let Some(name) = rest.split_whitespace().next() else {
                continue;
            };
            total.0 += usize::from(ok);
            total.1 += 1;
            let lower = name.rsplit('.').next().unwrap_or(name).to_ascii_lowercase();
            for id in criteria_of(&lower) {
                let r = results.entry(id).or_default();
                if ok { &mut r.passed } else { &mut r.failed }.push(name.to_string());
            }
        }
    }
    let q2_ok = std::fs::read_to_string("docs/WIRE_FORMAT.md").is_ok_and(|s| s.contains("## DATA"));

    let mut out = String::new();
    let scope = if all {
        "all milestones".to_string()
    } else {
        format!("up to {milestone}")
    };
    let _ = writeln!(out, "# Acceptance report ({scope})\n");
    let _ = writeln!(out, "| ID | Milestone | Criterion | Evidence | Status |");
    let _ = writeln!(out, "|----|-----------|-----------|----------|--------|");
    let mut all_green = true;
    for &(id, m, desc) in CRITERIA {
        if !in_scope(m) {
            continue;
        }
        let (evidence, status) = match id {
            "Q1" => {
                let deny = if deny_missing {
                    "deny: not installed (runs in CI)".to_string()
                } else {
                    format!("deny {}", if deny_ok { "ok" } else { "FAILED" })
                };
                let ok = fmt_ok && clippy_ok && (deny_ok || deny_missing);
                (
                    format!(
                        "fmt {}, clippy {}, {deny}",
                        if fmt_ok { "ok" } else { "FAILED" },
                        if clippy_ok { "ok" } else { "FAILED" }
                    ),
                    ok,
                )
            }
            "Q2" => ("docs/WIRE_FORMAT.md".into(), q2_ok),
            "T1" | "T2" | "T3" | "T4" | "T5" | "T7" | "Q3" => coverage_evidence(id),
            "X1" => (
                "workflow Unity package, job native (CI only)".into(),
                std::fs::read_to_string(".github/workflows/unity.yml").is_ok_and(|w| {
                    ["aarch64-apple-ios", "cargo ndk", "lipo -create", "windows-latest"]
                        .iter()
                        .all(|k| w.contains(k))
                }),
            ),
            "P4" => {
                let lib = [
                    "target/release/libnetlib_ffi.so",
                    "target/release/libnetlib_ffi.dylib",
                    "target/release/netlib_ffi.dll",
                ]
                .iter()
                .find_map(|p| std::fs::metadata(p).ok().map(|m| (*p, m.len())));
                match lib {
                    Some((p, n)) => (format!("{p}: {n} bytes (all platforms checked in CI)"), n < 1 << 20),
                    None => ("build with cargo build --release -p netlib-ffi".into(), false),
                }
            }
            "X4" => {
                let ok = |args: &[&str]| run("dotnet", args).0;
                let built = run(&cargo, &["xtask", "unity-package"]).0
                    && ok(&["build", "unity/ci", "--nologo"])
                    && ok(&["build", "unity/ci", "--nologo", "-p:DefineConstants=UNITY_IOS"]);
                (
                    "unity/ci compiles (C# 9, netstandard2.1, iOS branch); IL2CPP on device: docs/UNITY.md".into(),
                    built,
                )
            }
            "T6" => {
                // Criteria up to the selected milestone (M7 at most) without any test.
                let untraced: Vec<&str> = CRITERIA
                    .iter()
                    .filter(|(cid, m, _)| {
                        let rank = MILESTONES.iter().position(|x| x == m).unwrap_or(usize::MAX);
                        rank <= upto.min(7) && !cid.starts_with('T') && !["Q1", "Q2", "Q3"].contains(cid)
                    })
                    .filter(|(cid, _, _)| results.get(*cid).is_none_or(|r| r.passed.is_empty()))
                    .map(|(cid, _, _)| *cid)
                    .collect();
                if untraced.is_empty() {
                    ("all criteria have passing tests".into(), true)
                } else {
                    (format!("untraced: {}", untraced.join(", ")), false)
                }
            }
            "X2" => {
                let (ok, _) = run(&cargo, &["xtask", "header", "--check"]);
                let tests = results.get("X2").map_or((0, 0), |r| (r.passed.len(), r.failed.len()));
                (
                    format!(
                        "header {}, {}/{} tests",
                        if ok { "up to date" } else { "STALE" },
                        tests.0,
                        tests.0 + tests.1
                    ),
                    ok && tests.1 == 0 && tests.0 > 0,
                )
            }
            _ => match results.get(&id.to_ascii_uppercase()) {
                Some(r) => (
                    format!("{}/{} tests", r.passed.len(), r.passed.len() + r.failed.len()),
                    r.failed.is_empty(),
                ),
                None => {
                    let _ = writeln!(out, "| {id} | {m} | {desc} | no tests yet | ⏳ |");
                    if m == milestone {
                        all_green = false;
                    }
                    continue;
                }
            },
        };
        all_green &= status;
        let _ = writeln!(
            out,
            "| {id} | {m} | {desc} | {evidence} | {} |",
            if status { "✅" } else { "❌" }
        );
    }
    let _ = writeln!(out, "\nAll tests: {}/{} passed.", total.0, total.1);
    let failed: Vec<&String> = results.values().flat_map(|r| &r.failed).collect();
    if !failed.is_empty() {
        let _ = writeln!(out, "\nFailed criterion tests:");
        for f in failed {
            let _ = writeln!(out, "- `{f}`");
        }
    }
    if !clippy_ok {
        let _ = writeln!(out, "\n```\n{}\n```", clippy_out.trim());
    }
    print!("{out}");
    let _ = std::fs::create_dir_all("target");
    let _ = std::fs::write("target/report.md", &out);
    if all_green && tests_ok {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}

